async function seed() {
  console.log(`\nduty_matrix 시드 시작 (${ROWS.length}행)...\n`);

  // 전체 재적재 (재실행해도 중복 없이 항상 PDF 최신 상태와 동일하게 유지)
  const { error: delErr } = await supabase.from('duty_matrix').delete().gte('id', 0);
  if (delErr) { console.error('❌ 기존 데이터 삭제 오류:', delErr.message); process.exit(1); }

  const records = ROWS.map(([disaster, controller, shift, division, badge, dept_code]) => ({
    disaster, controller, shift, division, badge, dept_code,
  }));

  const { error: insErr } = await supabase.from('duty_matrix').insert(records);
  if (insErr) { console.error('❌ 삽입 오류:', insErr.message); process.exit(1); }

  console.log(`✅ 완료: duty_matrix ${records.length}행 적재`);
  const byDisaster = records.reduce<Record<string, number>>((acc, r) => {
    acc[r.disaster] = (acc[r.disaster] ?? 0) + 1;
    return acc;
  }, {});
  Object.entries(byDisaster).forEach(([d, n]) => console.log(`  - ${d}: ${n}행`));
}

seed().catch(err => { console.error('❌ 실패:', err); process.exit(1); });
