const DRAWINGS_DIR = resolve('C:/kcoding/disa_app/images/facility/outdoor');

async function main() {
  const label = '실외기 현황 및 도면';

  let { data: cat } = await supabase.from('facility_categories').select('id').eq('label', label).maybeSingle();
  if (!cat) {
    const { data: inserted, error } = await supabase
      .from('facility_categories')
      .insert({ disaster: '화재', label, icon: '🌀', sort_order: 10 })
      .select('id')
      .single();
    if (error) throw error;
    cat = inserted;
    console.log('✅ 카테고리 생성:', label, 'id=', cat!.id);
  } else {
    console.log('ℹ️ 카테고리 기존 재사용:', label, 'id=', cat.id);
  }
  const categoryId = cat!.id as number;

  await supabase.from('facility_items').delete().eq('category_id', categoryId);
  await supabase.from('facility_drawings').delete().eq('category_id', categoryId);

  const itemRows = ROWS.map(([floor, building, loc, qty, name, breaker, model, vendor], i) => ({
    category_id: categoryId,
    name: name || model,
    spec: model,
    qty,
    building,
    floor,
    location: loc,
    note: null,
    attrs: { breaker: breaker || null, vendor: vendor || null },
    sort_order: i,
  }));
  const { error: itemsErr } = await supabase.from('facility_items').insert(itemRows);
  if (itemsErr) throw itemsErr;
  console.log(`✅ 실외기 항목 ${itemRows.length}건 등록 완료`);

  for (let i = 0; i < DRAWINGS.length; i++) {
    const d = DRAWINGS[i];
    const filePath = resolve(DRAWINGS_DIR, d.file);
    const fileBuf = readFileSync(filePath);
    const storagePath = `outdoor/${d.file}`;
    const { error: upErr } = await supabase.storage
      .from('facility-drawings')
      .upload(storagePath, fileBuf, { contentType: 'image/png', upsert: true });
    if (upErr) throw upErr;

    const { error: rowErr } = await supabase.from('facility_drawings').insert({
      category_id: categoryId,
      title: d.title,
      building: d.building,
      floor: d.floor,
      storage_path: storagePath,
      sort_order: i,
    });
    if (rowErr) throw rowErr;
    console.log('✅ 도면 업로드+등록:', d.title);
  }

  console.log('🎉 완료');
}

main().catch(e => {
  console.error('❌ 실패:', e);
  process.exit(1);
});
